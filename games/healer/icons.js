function shape(part) {
  const dim = part.dim ? ' opacity=".45"' : '';
  // 채운 도형은 테두리를 끄지 않으면 선 굵기만큼 부풀어 옆 도형과 붙는다.
  const fill = part.f ? ' fill="currentColor" stroke="none"' : '';
  if (part.c) {
    const [cx, cy, r] = part.c;
    return `<circle cx="${cx}" cy="${cy}" r="${r}"${fill}${dim}/>`;
  }
  return `<path d="${part.d}"${fill}${dim}/>`;
}

const cache = new Map();

// 모르는 이름이 와도 화면이 비지 않아야 한다 — 아이콘 하나가 빠졌다고 스킬을
// 못 누르게 되면 곤란하다.
const FALLBACK = [{ c: [12, 12, 7] }];

function svg(name, cls) {
  const key = `${name}|${cls || ''}`;
  if (cache.has(key)) return cache.get(key);
  const parts = (ICONS[name] || FALLBACK).map(shape).join('');
  const markup = `<svg class="ico${cls ? ` ${cls}` : ''}" viewBox="0 0 ${BOX} ${BOX}"`
    + ' fill="none" stroke="currentColor" stroke-width="' + STROKE + '"'
    + ` stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${parts}</svg>`;
  cache.set(key, markup);
  return markup;
}

