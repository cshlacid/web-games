const round = (n) => Math.round(n * 100) / 100;
const color = (key) => PALETTE[key] || OUTLINE;

// 테두리 굵기. 화면에서 유닛 하나가 폭 40px 남짓이라 이보다 얇으면 밝은 배경에서
// 실루엣이 풀리고, 굵으면 이 크기에서 얼굴이 선에 먹힌다.
const STROKE = 0.42;

function shape(part) {
  const fill = color(part.f);
  // 활처럼 채우면 안 되는 것. 선 하나로 긋고 테두리를 따로 두르지 않는다 —
  // 두르면 활이 막대가 된다.
  if (part.arc) {
    return `<path d="${part.arc}" fill="none" stroke="${fill}"`
      + ` stroke-width="${part.width}" stroke-linecap="round"/>`;
  }
  const line = part.o === 0 ? '' : ` stroke="${OUTLINE}" stroke-width="${STROKE}"`;
  if (part.e) {
    const [cx, cy, rx, ry] = part.e.map(round);
    return `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}"${line}/>`;
  }
  if (part.r) {
    const [x, y, w, h, rd] = part.r.map(round);
    return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rd}" fill="${fill}"${line}/>`;
  }
  return `<path d="${part.p}" fill="${fill}"${line}/>`;
}

const cache = new Map();

function svg(kind) {
  if (cache.has(kind)) return cache.get(kind);
  const sprite = SPRITES[kind] || SPRITES.warrior;
  const parts = sprite.parts.map(shape).join('');
  // 테두리가 바깥으로 반 굵기 삐져나가고, 뿔이나 검이 격자를 조금 넘는다.
  // 여유 한 칸을 두지 않으면 그것들이 잘린다.
  const markup = `<svg class="sprite" viewBox="-1 -1 ${sprite.w + 2} ${sprite.h + 2}"`
    + ` stroke-linejoin="round" aria-hidden="true">${parts}</svg>`;
  cache.set(kind, markup);
  return markup;
}

// 그림마다 폭이 다르다. 화면에서 실제 크기를 그 폭에 맞추려면 밖에서도 알아야
// 한다 — 우두머리를 넓게 그린 것이 곧 크게 보이는 것이라는 규칙이 여기서만
// 지켜지면 소용이 없다.
function size(kind) {
  const sprite = SPRITES[kind] || SPRITES.warrior;
  return { w: sprite.w + 2, h: sprite.h + 2 };
}

