// '#'을 칠한 칸으로 읽는다. 사람이 눈으로 그림을 그릴 수 있는 꼴이 자료로도 낫다.
function cellsOf(rows) {
  const out = [];
  for (const row of rows) for (const ch of row) out.push(ch === '#' ? 1 : 0);
  return out;
}

